package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"image"
	"image/png"
	"log"
	"os"
	"strings"
)

const (
	opaqueAlpha = 60
	inkAlpha    = 110
	zzzTop      = 0.2
	zzzLeft     = 0.55
)

var sizes = []int{48, 32, 24}

type sample struct {
	r, g, b, a float64
}

func main() {
	in := flag.String("in", "", "logo PNG to sample")
	out := flag.String("out", "", "Go file to write")
	pkg := flag.String("pkg", "screens", "package of the generated file")
	flag.Parse()
	if *in == "" || *out == "" {
		log.Fatal("logo_gen: -in and -out are required")
	}
	img, err := decode(*in)
	if err != nil {
		log.Fatalf("logo_gen: %v", err)
	}
	src, err := render(*pkg, img)
	if err != nil {
		log.Fatalf("logo_gen: %v", err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatalf("logo_gen: %v", err)
	}
}

func decode(path string) (image.Image, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	return png.Decode(f)
}

func render(pkg string, img image.Image) ([]byte, error) {
	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by scripts/logo_gen from docs/images/logo.png; DO NOT EDIT.\n\npackage %s\n\n", pkg)
	buf.WriteString("var logoGrids = map[int][]string{\n")
	square := squareBounds(img)
	for _, size := range sizes {
		fmt.Fprintf(&buf, "\t%d: {\n", size)
		for _, row := range grid(img, square, size) {
			fmt.Fprintf(&buf, "\t\t%q,\n", row)
		}
		buf.WriteString("\t},\n")
	}
	buf.WriteString("}\n")
	return format.Source(buf.Bytes())
}

func squareBounds(img image.Image) image.Rectangle {
	b := img.Bounds()
	ink := image.Rectangle{Min: b.Max, Max: b.Min}
	for y := b.Min.Y; y < b.Max.Y; y++ {
		for x := b.Min.X; x < b.Max.X; x++ {
			if alpha(img, x, y) > opaqueAlpha {
				ink = ink.Union(image.Rect(x, y, x+1, y+1))
			}
		}
	}
	side := max(ink.Dx(), ink.Dy())
	min := image.Pt(ink.Min.X-(side-ink.Dx())/2, ink.Min.Y-(side-ink.Dy())/2)
	return image.Rectangle{Min: min, Max: min.Add(image.Pt(side, side))}
}

func alpha(img image.Image, x, y int) uint32 {
	_, _, _, a := img.At(x, y).RGBA()
	return a >> 8
}

func grid(img image.Image, square image.Rectangle, size int) []string {
	rows := make([][]byte, size)
	for y := range rows {
		rows[y] = make([]byte, size)
		for x := range rows[y] {
			rows[y][x] = classify(average(img, cell(square, size, x, y)), x, y, size)
		}
	}
	fillPaper(rows)
	smooth(rows)
	return trim(rows)
}

func cell(square image.Rectangle, size, x, y int) image.Rectangle {
	scale := float64(square.Dx()) / float64(size)
	return image.Rect(
		square.Min.X+int(float64(x)*scale), square.Min.Y+int(float64(y)*scale),
		square.Min.X+int(float64(x+1)*scale), square.Min.Y+int(float64(y+1)*scale),
	)
}

func average(img image.Image, area image.Rectangle) sample {
	var s sample
	n := float64(area.Dx() * area.Dy())
	for y := area.Min.Y; y < area.Max.Y; y++ {
		for x := area.Min.X; x < area.Max.X; x++ {
			if !(image.Point{X: x, Y: y}).In(img.Bounds()) {
				continue
			}
			r, g, b, a := img.At(x, y).RGBA()
			s.r += float64(r >> 8)
			s.g += float64(g >> 8)
			s.b += float64(b >> 8)
			s.a += float64(a >> 8)
		}
	}
	if s.a == 0 {
		return sample{}
	}
	return sample{r: s.r * 255 / s.a, g: s.g * 255 / s.a, b: s.b * 255 / s.a, a: s.a / n}
}

func classify(s sample, x, y, size int) byte {
	if s.a < inkAlpha {
		return '.'
	}
	luma := 0.2126*s.r + 0.7152*s.g + 0.0722*s.b
	if luma > 200 {
		return 'w'
	}
	if float64(y) < float64(size)*zzzTop && float64(x) > float64(size)*zzzLeft {
		return 'z'
	}
	switch {
	case luma > 130:
		return 'c'
	case s.b > 0 && s.r/s.b < 0.02 && s.g < 92:
		return 'a'
	default:
		return 'b'
	}
}

func fillPaper(rows [][]byte) {
	panel, wall := mode(rows, 'a'), mode(rows, 0)
	reach := len(rows) / 6
	for _, row := range rows {
		left, right := firstInk(row), strings.IndexByte(string(row), 'a')
		if right < panel || right > panel+reach || left < 0 || left > wall+reach {
			continue
		}
		for x := left; x < right; x++ {
			if row[x] == '.' {
				row[x] = 'w'
			}
		}
	}
}

func mode(rows [][]byte, ch byte) int {
	counts := map[int]int{}
	best, bestCount := -1, 0
	for _, row := range rows {
		if strings.IndexByte(string(row), 'a') < 0 {
			continue
		}
		x := firstInk(row)
		if ch != 0 {
			x = strings.IndexByte(string(row), ch)
		}
		counts[x]++
		if counts[x] > bestCount || (counts[x] == bestCount && x < best) {
			best, bestCount = x, counts[x]
		}
	}
	return best
}

func firstInk(row []byte) int {
	for x, ch := range row {
		if ch != '.' {
			return x
		}
	}
	return -1
}

func smooth(rows [][]byte) {
	for _, row := range rows {
		for x := 1; x < len(row)-1; x++ {
			switch {
			case row[x] == 'a' && row[x-1] == 'b' && row[x+1] == 'b':
				row[x] = 'b'
			case row[x] == 'b' && row[x-1] == 'a' && row[x+1] == 'a':
				row[x] = 'a'
			}
		}
	}
}

func trim(rows [][]byte) []string {
	out := make([]string, 0, len(rows))
	for _, row := range rows {
		out = append(out, string(row))
	}
	for len(out) > 0 && strings.Trim(out[len(out)-1], ".") == "" {
		out = out[:len(out)-1]
	}
	if len(out)%2 == 1 {
		out = append(out, strings.Repeat(".", len(rows[0])))
	}
	return out
}
